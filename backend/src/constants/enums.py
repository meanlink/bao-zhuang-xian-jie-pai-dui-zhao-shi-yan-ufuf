from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class ReleaseScope(str, Enum):
    overall = 'overall'
    by_shift = 'by_shift'
class ReleaseStatus(str, Enum):
    pending = 'pending'
    delivered = 'delivered'
    rejected = 'rejected'
class DeliveryStatus(str, Enum):
    publishing = 'publishing'
    delivered = 'delivered'
